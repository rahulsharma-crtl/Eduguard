import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
const output = 'components/student_room/frontend/engagement.js';
const result = await build({ entryPoints: ['core/engagement.mjs'], bundle: true,
    format: 'iife', globalName: 'EduGuardEngagement', target: 'es2020', write: false,
    banner: { js: '// Generated by npm run build:engagement; edit core/engagement.mjs only.' } });
const code = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== code) throw new Error('Browser bundle is stale. Run npm run build:engagement');
} else writeFileSync(output, code);

const rosterOutput = 'components/teacher_room/frontend/roster.js';
const roster = await build({ entryPoints: ['core/roster.mjs'], bundle: true, format: 'iife',
    globalName: 'EduGuardRoster', target: 'es2020', write: false,
    banner: { js: '// Generated by npm run build:engagement; edit core/roster.mjs only.' } });
if (process.argv.includes('--check')) {
    if (readFileSync(rosterOutput, 'utf8') !== roster.outputFiles[0].text) throw new Error('Roster bundle is stale');
} else writeFileSync(rosterOutput, roster.outputFiles[0].text);
